// Распиновка и параметры клиента. Wi-Fi, адрес сервера и имя комнаты задаются
// через веб-портал при первом запуске (точка доступа "Irene-XXXXXX"), а не здесь.
// Усиление, порог и паузу потом удобнее менять в веб-интерфейсе сервера (вкладка «Комнаты»).
#pragma once

#define FW_VERSION "3.0"

// ---------------- распиновка ----------------
#if defined(CONFIG_IDF_TARGET_ESP32S3)
  // ESP32-S3 (модуль S3-N16R8 / ESP32-S3-WROOM-1 или плата DevKitC-1).
  // В адаптере для WROOM-32E эти выводы подписаны: SVP, SVN, IO34, IO35, IO32, IO33.
  // GPIO 35, 36, 37 заняты памятью PSRAM (модули R8) — ничего к ним не подключать.
  #define MIC_SCK   4    // INMP441 SCK          (адаптер: SVP)
  #define MIC_WS    5    // INMP441 WS           (адаптер: SVN)
  #define MIC_SD    6    // INMP441 SD           (адаптер: IO34)
  #define AMP_DIN   7    // MAX98357A DIN        (адаптер: IO35)
  #define AMP_BCLK  15   // MAX98357A BCLK       (адаптер: IO32)
  #define AMP_LRC   16   // MAX98357A LRC        (адаптер: IO33)
  #define AMP_SD    -1   // MAX98357A SD: -1 — не подключён (можно GPIO17 = «IO25» на адаптере)
  #define LED_PIN   -1   // светодиод «слушаю»: -1 — нет (светодиод адаптера «LED-IO4» сидит на GPIO35/PSRAM — не трогать)
  #define AUDIO_BUF_BYTES (64 * 1024)   // буфер ответа (в PSRAM, если она есть)
  #define SNAP_RING_MS    3000          // очередь музыки, мс (в PSRAM): больше буфера snapserver (1000 мс) с запасом
#else
  // ESP32 DevKit (WROOM-32)
  #define MIC_SCK   32
  #define MIC_WS    25
  #define MIC_SD    33
  #define AMP_BCLK  26
  #define AMP_LRC   27
  #define AMP_DIN   22
  #define AMP_SD    -1
  #define LED_PIN   2    // встроенный светодиод
  #define AUDIO_BUF_BYTES (24 * 1024)
  #define SNAP_RING_MS    1400          // без PSRAM память дорогая: чуть больше буфера snapserver
#endif

#define RESET_BUTTON 0     // кнопка BOOT/PROG: удерживать 5 секунд — сброс настроек Wi-Fi и комнаты

// ---------------- микрофон ----------------
// INMP441 отдаёт звук только в одном слоте I2S (L/R на GND — левый). Клиент читает оба и сам выбирает живой
// (в мониторе порта: «Микрофон: слот …»). -1 — автоматически; 0 или 1 — задать вручную.
#define MIC_SLOT          -1
#define DEFAULT_MIC_GAIN_DB 12   // начальное усиление микрофона, дБ (0..30)
#define DEFAULT_VAD_LEVEL   250  // порог речи (RMS). Меньше — чувствительнее, больше — меньше ложных срабатываний

// ---------------- автоусиление (АРУ) ----------------
// Медленная подстройка только по речи: после каждой фразы усиление сдвигается к цели,
// посреди фразы не меняется, шум не поднимается выше порога, при перегрузке — сразу вниз.
#define DEFAULT_AGC        1     // 1 — автоусиление включено
#define DEFAULT_AGC_MAX_DB 30    // верхняя граница автоусиления, дБ
#define AGC_TARGET         2500  // целевой уровень речи (хорошо распознаётся: 1500–5000)
#define AGC_STEP_MAX_DB    3.0f  // не больше стольких дБ за одну фразу
#define AGC_MIN_DB         6     // ниже автоусиление не опускается (ручное — можно до 0)
#define AGC_NOISE_MAX      400   // фоновый шум после усиления не выше этого: порог речи (шум × 3) остаётся ниже цели
#define AGC_CLIP_LEVEL     15000 // уровень фразы выше — искажения: усиление снижается без раздумий
#define AGC_CLIP_FRAMES    10    // столько кадров с перегрузкой за громкую фразу (0,2 с) — тоже снижаем
#define AGC_SAVE_MS        300000 // подобранное усиление сохраняется раз в 5 минут

// ---------------- детектор речи (VAD) ----------------
#define VAD_START_RATIO   3.0f   // во сколько раз громче фонового шума считается речью
#define VAD_START_FRAMES  3      // столько кадров по 20 мс подряд, чтобы начать
#define DEFAULT_VAD_HANG_MS 1000 // сколько тишины ждать до конца фразы (после "Ирина" — вдвое дольше)
#define VAD_PREROLL_MS    400    // сколько звука до начала речи отправить (чтобы не съесть начало слова)
#define VAD_MAX_MS        12000  // максимальная длина фразы
#define MIC_MUTE_AFTER_TTS_MS 350 // не слушать микрофон сразу после ответа (эхо)
#define METER_INTERVAL_MS 250    // живой индикатор для веб-интерфейса (шлётся, только пока страница открыта)

// ---------------- музыка (мультирум Snapcast) ----------------
// Клиент сам подключается к snapserver на том же адресе, что и сервер Ирины, с ID = ID комнаты.
// Какую музыку играет комната, решает Ирина (голосом: «добавь кухню», «как в спальне» — или на странице «Комнаты»).
#define SNAP_ENABLED     1       // 0 — клиент без музыки, как прошивка 2.x
#define SNAP_PORT        1704
#define MUSIC_DUCK_PCT   20      // громкость музыки, пока Ирина слушает команду и отвечает, % от обычной
#define MUSIC_VAD_RATIO  4.0f    // пока играет музыка, речь должна быть во столько раз громче фона (музыки в микрофоне)

// ---------------- Wi-Fi ----------------
// Если клиент перезагружается или теряет сеть, когда говорит (просадка питания) —
// попробуйте WIFI_POWER_15dBm. Если далеко от роутера — WIFI_POWER_19_5dBm (максимум).
#define WIFI_TX_POWER    WIFI_POWER_19_5dBm

#define DEFAULT_SERVER   "irene.local"
#define DEFAULT_PORT     8765
#define DEFAULT_VOLUME   70
// Предел громкости усилителя, % от полной. На 100% динамик 4 Ом берёт пики больше 1 А по 5 В —
// слабый блок питания или тонкий кабель просаживаются, и модуль перезагружается (brownout).
// С хорошим блоком 5 В 2 А и коротким толстым проводом можно поставить 100.
#define VOLUME_LIMIT_PCT 80
