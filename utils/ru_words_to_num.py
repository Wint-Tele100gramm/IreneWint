# Перевод русских числительных из распознанной речи в число: "пятьдесят пять" -> 55.
# Vosk выдаёт числа словами, поэтому для "яркость пятьдесят" / "громкость тридцать" нужен обратный перевод.

_UNITS = {
    "ноль": 0, "нуль": 0,
    "один": 1, "одна": 1, "одну": 1, "одно": 1,
    "два": 2, "две": 2, "три": 3, "четыре": 4, "пять": 5, "шесть": 6,
    "семь": 7, "восемь": 8, "девять": 9, "десять": 10,
    "одиннадцать": 11, "двенадцать": 12, "тринадцать": 13, "четырнадцать": 14,
    "пятнадцать": 15, "шестнадцать": 16, "семнадцать": 17, "восемнадцать": 18,
    "девятнадцать": 19,
}
_TENS = {
    "двадцать": 20, "тридцать": 30, "сорок": 40, "пятьдесят": 50,
    "шестьдесят": 60, "семьдесят": 70, "восемьдесят": 80, "девяносто": 90,
}
_HUNDREDS = {"сто": 100, "двести": 200, "триста": 300}
_SPECIAL = {"половина": 50, "половину": 50, "максимум": 100, "максимальную": 100, "минимум": 1}


def extract_number(text: str):
    """Возвращает первое число из фразы (цифрами или словами) или None."""
    total = None
    for word in text.lower().replace("ё", "е").split():
        if word.isdigit():
            return int(word)
        if word.endswith("%") and word[:-1].isdigit():
            return int(word[:-1])
        if word in _SPECIAL and total is None:
            return _SPECIAL[word]
        value = _HUNDREDS.get(word, _TENS.get(word, _UNITS.get(word)))
        if value is None:
            if total is not None:
                break  # число закончилось
            continue
        total = (total or 0) + value
    return total


if __name__ == "__main__":
    for t in ["яркость пятьдесят пять процентов", "громкость 30", "на половину", "двадцать два градуса", "свет"]:
        print(t, "->", extract_number(t))
