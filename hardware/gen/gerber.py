# Выпуск производственных файлов: Gerber RS-274X (медь, маска, паста, шелкография, контур) и сверловка Excellon.
# Заливка земли на обоих слоях строится полярностью слоя (LPD/LPC): сплошная медь, вырезы вокруг чужих цепей,
# затем сами проводники. Островки и тонкие перемычки находятся растром (numpy) и либо пришиваются
# переходными отверстиями к земле другого слоя, либо вырезаются.

import math

import numpy as np
from PIL import Image, ImageDraw
from scipy import ndimage

from placement import W, H, CORNER_R, ANTENNA_KEEPOUT

POUR_CLEAR = 0.4        # зазор заливки до чужих цепей
EDGE_CLEAR = 0.4        # от края платы
MASK_EXP = 0.05         # расширение окон маски
MIN_POUR = 0.25         # минимальная ширина заливки
THERMAL_W = 0.5         # ширина перемычек термобарьера у выводов в отверстиях
STITCH_STEP = 8.0       # шаг сшивающих переходных отверстий
STITCH_VIA = (0.6, 0.3)
RES = 40                # пикселей на мм для анализа заливки


def fmt(v):
    return str(int(round(v * 1e6)))


class Gerber:
    def __init__(self, function, polarity="Positive"):
        self.function = function
        self.polarity = polarity
        self.aps = {}
        self.body = []
        self.cur = None

    def ap(self, kind, *dims):
        key = (kind,) + tuple(round(d, 4) for d in dims)
        if key not in self.aps:
            self.aps[key] = 10 + len(self.aps)
        code = self.aps[key]
        if self.cur != code:
            self.body.append(f"D{code}*")
            self.cur = code
        return code

    def flash(self, x, y):
        self.body.append(f"X{fmt(x)}Y{fmt(H - y)}D03*")

    def line(self, x1, y1, x2, y2):
        self.body.append(f"X{fmt(x1)}Y{fmt(H - y1)}D02*")
        self.body.append(f"X{fmt(x2)}Y{fmt(H - y2)}D01*")

    def polyline(self, pts):
        self.body.append(f"X{fmt(pts[0][0])}Y{fmt(H - pts[0][1])}D02*")
        for x, y in pts[1:]:
            self.body.append(f"X{fmt(x)}Y{fmt(H - y)}D01*")

    def region(self, pts):
        self.body.append("G36*")
        self.polyline(list(pts) + [pts[0]])
        self.body.append("G37*")

    def lp(self, dark):
        self.body.append("%LPD*%" if dark else "%LPC*%")

    def text(self):
        out = ["G04 Irene client board, generated by hardware/gen/build.py*",
               f"%TF.FileFunction,{self.function}*%",
               f"%TF.FilePolarity,{self.polarity}*%",
               "%FSLAX46Y46*%", "%MOMM*%", "%LPD*%", "G01*", "G75*"]
        for key, code in sorted(self.aps.items(), key=lambda kv: kv[1]):
            kind, dims = key[0], key[1:]
            out.append(f"%ADD{code}{kind}," + "X".join(f"{d:.4f}" for d in dims) + "*%")
        return "\n".join(out + self.body + ["M02*", ""])


def rrect_pts(x1, y1, x2, y2, r, n=4):
    r = max(0.0, min(r, (x2 - x1) / 2, (y2 - y1) / 2))
    if r < 1e-4:
        return [(x1, y1), (x2, y1), (x2, y2), (x1, y2)]
    pts = []
    for cx, cy, a0 in ((x2 - r, y1 + r, -90), (x2 - r, y2 - r, 0), (x1 + r, y2 - r, 90), (x1 + r, y1 + r, 180)):
        for i in range(n + 1):
            a = math.radians(a0 + 90 * i / n)
            pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    return pts


def board_outline_pts(inset=0.0, n=6):
    return rrect_pts(inset, inset, W - inset, H - inset, max(CORNER_R - inset, 0), n)


def draw_pad(g, pad, grow=0.0):
    w, h = pad.w + 2 * grow, pad.h + 2 * grow
    if pad.shape == "circle" or (pad.shape == "oval" and abs(w - h) < 1e-6):
        g.ap("C", w)
        g.flash(pad.x, pad.y)
    elif pad.shape == "oval":
        g.ap("O", w, h)
        g.flash(pad.x, pad.y)
    elif pad.shape == "roundrect":
        r = min(pad.w, pad.h) * pad.rr + grow
        g.region(rrect_pts(pad.x - w / 2, pad.y - h / 2, pad.x + w / 2, pad.y + h / 2, r))
    else:
        g.ap("R", w, h)
        g.flash(pad.x, pad.y)


def thermal_spokes(pad, parts, tracks, vias):
    """Перемычки термобарьера, которые не подходят к чужим цепям ближе зазора заливки."""
    from check import _seg_dist, _seg_seg
    L = max(pad.w, pad.h) / 2 + POUR_CLEAR + 0.15
    out = []
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        seg = (pad.x, pad.y, pad.x + dx * L, pad.y + dy * L)
        ok = True
        for p in parts:
            for o in p.pads:
                if o is pad or o.npth or o.net == "GND" or not (o.layers & pad.layers):
                    continue
                if abs(o.x - pad.x) > 6 or abs(o.y - pad.y) > 6:
                    continue
                r = max(o.w, o.h) / 2
                if _seg_dist(o.x, o.y, *seg) - r - THERMAL_W / 2 < POUR_CLEAR:
                    ok = False
        for t in tracks:
            if t["net"] != "GND" and _seg_seg(seg, t["pts"]) - t["w"] / 2 - THERMAL_W / 2 < POUR_CLEAR:
                ok = False
        for v in vias:
            if v["net"] != "GND" and _seg_dist(v["x"], v["y"], *seg) - v["d"] / 2 - THERMAL_W / 2 < POUR_CLEAR:
                ok = False
        if ok:
            out.append(seg)
    return out


# ---------------------------------------------------------------- растр для анализа заливки

def _P(x, y):
    return (x * RES, y * RES)


def _r_pad(d, pad, grow=0.0):
    w, h = pad.w + 2 * grow, pad.h + 2 * grow
    box = [*_P(pad.x - w / 2, pad.y - h / 2), *_P(pad.x + w / 2, pad.y + h / 2)]
    if pad.shape == "circle":
        d.ellipse(box, fill=1)
    elif pad.shape in ("oval", "roundrect"):
        r = min(w, h) / 2 if pad.shape == "oval" else min(pad.w, pad.h) * pad.rr + grow
        d.rounded_rectangle(box, radius=r * RES, fill=1)
    else:
        d.rectangle(box, fill=1)


def _r_seg(d, x1, y1, x2, y2, w):
    d.line([_P(x1, y1), _P(x2, y2)], fill=1, width=max(1, int(round(w * RES))))
    r = w / 2
    for x, y in ((x1, y1), (x2, y2)):
        d.ellipse([*_P(x - r, y - r), *_P(x + r, y + r)], fill=1)


def _r_circle(d, x, y, dia):
    r = dia / 2
    d.ellipse([*_P(x - r, y - r), *_P(x + r, y + r)], fill=1)


def _blank():
    img = Image.new("1", (int(W * RES) + 1, int(H * RES) + 1), 0)
    return img, ImageDraw.Draw(img)


def _arr(img):
    return np.array(img, dtype=bool)


def _disk(rpx):
    y, x = np.ogrid[-rpx:rpx + 1, -rpx:rpx + 1]
    return x * x + y * y <= rpx * rpx


class Pour:
    """Заливка земли на одном слое: что вырезать, острова, места для сшивки."""

    def __init__(self, side, parts, tracks, vias, extra_vias):
        self.side = side
        img, d = _blank()
        d.polygon([_P(x, y) for x, y in board_outline_pts(EDGE_CLEAR)], fill=1)
        pour = _arr(img)
        img, d = _blank()
        kx1, ky1, kx2, ky2 = ANTENNA_KEEPOUT
        d.rectangle([*_P(kx1, ky1), *_P(kx2, ky2)], fill=1)
        clear = _arr(img)
        img, d = _blank()      # вырез вокруг чужих цепей (с запасом в 1 пиксель)
        img2, d2 = _blank()    # медь земли на этом слое
        g = POUR_CLEAR + 1.0 / RES
        self.thermals = []
        for p in parts:
            for pad in p.pads:
                if pad.npth:
                    _r_circle(d, pad.x, pad.y, pad.w + 2 * 0.25)
                    continue
                if side not in pad.layers:
                    continue
                if pad.net == "GND":
                    if pad.drill:
                        # термобарьер: кольцо + 4 перемычки
                        _r_pad(d, pad, g)
                        self.thermals.append(pad)
                    _r_pad(d2, pad)
                else:
                    _r_pad(d, pad, g)
        for t in tracks:
            if t["layer"] != side:
                continue
            if t["net"] == "GND":
                _r_seg(d2, *t["pts"], t["w"])
            else:
                _r_seg(d, *t["pts"], t["w"] + 2 * g)
        for v in list(vias) + list(extra_vias):
            if v["net"] == "GND":
                _r_circle(d2, v["x"], v["y"], v["d"])
            else:
                _r_circle(d, v["x"], v["y"], v["d"] + 2 * g)
        cut = _arr(img)
        self.spokes = {}
        for pad in self.thermals:
            self.spokes[id(pad)] = thermal_spokes(pad, parts, tracks, list(vias) + list(extra_vias))
            for seg in self.spokes[id(pad)]:
                _r_seg(d2, *seg, THERMAL_W)
        self.gnd = _arr(img2)
        raw = pour & ~clear & ~cut
        # убрать полоски уже MIN_POUR (их не вытравить надёжно)
        k = _disk(int(math.ceil(MIN_POUR * RES / 2)))
        opened = ndimage.binary_opening(raw, structure=k)
        self.raw = raw
        self.pour = opened | (raw & ndimage.binary_dilation(self.gnd, iterations=1))
        self.labels, self.n = ndimage.label(self.pour)

    def comps_touching(self, mask):
        ids = np.unique(self.labels[mask & self.pour])
        return set(int(i) for i in ids if i)


def build_pours(parts, tracks, vias):
    """Заливки обоих слоёв, сшивка переходными отверстиями, удаление неподключённых островов."""
    stitch = []
    for _ in range(3):
        F = Pour("F", parts, tracks, vias, stitch)
        B = Pour("B", parts, tracks, vias, stitch)
        # граф: компоненты F/B + переходы/выводы в отверстиях земли
        parent = {}

        def f(a):
            parent.setdefault(a, a)
            while parent[a] != a:
                parent[a] = parent[parent[a]]
                a = parent[a]
            return a

        def u(a, b):
            parent[f(a)] = f(b)

        def item_mask(fn):
            img, d = _blank()
            fn(d)
            return _arr(img)
        gnd_items = []
        for v in list(vias) + stitch:
            if v["net"] == "GND":
                gnd_items.append(("via", v, item_mask(lambda d, v=v: _r_circle(d, v["x"], v["y"], v["d"])), "FB"))
        for p in parts:
            for pad in p.pads:
                if pad.net == "GND" and not pad.npth:
                    def draw(d, pad=pad):
                        _r_pad(d, pad)
                        if pad.drill:
                            for seg in F.spokes.get(id(pad), []) + B.spokes.get(id(pad), []):
                                _r_seg(d, *seg, THERMAL_W)
                    gnd_items.append(("pad", pad, item_mask(draw), "".join(sorted(pad.layers))))
        for t in tracks:
            if t["net"] == "GND":
                gnd_items.append(("trk", t, item_mask(lambda d, t=t: _r_seg(d, *t["pts"], t["w"])), t["layer"]))
        for i, (kind, obj, m, layers) in enumerate(gnd_items):
            f(("i", i))
            for side, P in (("F", F), ("B", B)):
                if side in layers:
                    grown = ndimage.binary_dilation(m, iterations=1)
                    for c in P.comps_touching(grown):
                        u(("i", i), (side, c))
        # одинаковые выводы одной детали соединены внутри неё; дорожки земли — через check.connectivity
        from check import connectivity
        from board import nets_of
        groups = connectivity(parts, [t for t in tracks if t["net"] == "GND"], [v for v in vias if v["net"] == "GND"],
                              nets_of(parts)).get("GND")
        pad_index = {id(obj): i for i, (kind, obj, m, l) in enumerate(gnd_items) if kind == "pad"}
        if groups:
            for grp in groups:
                for a, b in zip(grp, grp[1:]):
                    u(("i", pad_index[id(a)]), ("i", pad_index[id(b)]))
        else:
            pads = [i for i, it in enumerate(gnd_items) if it[0] == "pad"]
            for a, b in zip(pads, pads[1:]):
                u(("i", a), ("i", b))
        # главная группа — та, где больше всего площади заливки
        area = {}
        for side, P in (("F", F), ("B", B)):
            sizes = ndimage.sum(np.ones_like(P.labels), P.labels, range(1, P.n + 1))
            for c in range(1, P.n + 1):
                area[f((side, c))] = area.get(f((side, c)), 0) + sizes[c - 1]
        main = max(area, key=area.get)
        added = False
        # острова: пробуем пришить переходным отверстием к главной земле другого слоя
        rv = int(math.ceil((STITCH_VIA[0] / 2 + 0.15) * RES))
        k = _disk(rv)
        for side, P, O in (("F", F, B), ("B", B, F)):
            omain = np.zeros_like(O.pour)
            for c in range(1, O.n + 1):
                if f((O.side, c)) == main:
                    omain |= O.labels == c
            okern = ndimage.binary_erosion(omain, structure=k)
            for c in range(1, P.n + 1):
                if f((side, c)) == main:
                    continue
                isl = ndimage.binary_erosion(P.labels == c, structure=k) & okern
                ys, xs = np.nonzero(isl)
                if len(xs):
                    j = len(xs) // 2
                    stitch.append({"net": "GND", "x": xs[j] / RES, "y": ys[j] / RES, "d": STITCH_VIA[0], "drill": STITCH_VIA[1]})
                    added = True
        # регулярная сшивка там, где обе заливки — главная земля
        if not any(s.get("grid") for s in stitch):
            both = np.zeros_like(F.pour)
            mF = np.zeros_like(F.pour)
            for c in range(1, F.n + 1):
                if f(("F", c)) == main:
                    mF |= F.labels == c
            mB = np.zeros_like(B.pour)
            for c in range(1, B.n + 1):
                if f(("B", c)) == main:
                    mB |= B.labels == c
            k2 = _disk(int(math.ceil((STITCH_VIA[0] / 2 + 0.35) * RES)))
            both = ndimage.binary_erosion(mF, structure=k2) & ndimage.binary_erosion(mB, structure=k2)
            step = int(STITCH_STEP * RES)
            taken = []
            for yy in range(step // 2, both.shape[0], step):
                for xx in range(step // 2, both.shape[1], step):
                    # ищем ближайшую подходящую точку в клетке
                    cell = both[max(0, yy - step // 2):yy + step // 2, max(0, xx - step // 2):xx + step // 2]
                    ys, xs = np.nonzero(cell)
                    if not len(xs):
                        continue
                    j = np.argmin((ys - step // 2) ** 2 + (xs - step // 2) ** 2)
                    x = (max(0, xx - step // 2) + xs[j]) / RES
                    y = (max(0, yy - step // 2) + ys[j]) / RES
                    if any(math.hypot(x - a, y - b) < STITCH_STEP * 0.6 for a, b in taken):
                        continue
                    taken.append((x, y))
                    stitch.append({"net": "GND", "x": x, "y": y, "d": STITCH_VIA[0], "drill": STITCH_VIA[1], "grid": True})
            added = True
        if not added:
            break
    # итог: что вырезать (полоски и неподключённые острова), список земляных выводов без связи
    result = {"stitch": stitch, "remove": {}, "orphans": [], "pours": {"F": F, "B": B}}
    for side, P in (("F", F), ("B", B)):
        keep = np.zeros_like(P.pour)
        for c in range(1, P.n + 1):
            if f((side, c)) == main:
                keep |= P.labels == c
        remove = P.raw & ~keep
        result["remove"][side] = ndimage.binary_dilation(remove, iterations=2) & ~keep
        result["pours"][side + "_keep"] = keep
    for i, (kind, obj, m, layers) in enumerate(gnd_items):
        if kind == "pad" and f(("i", i)) != main:
            result["orphans"].append(f"{obj.ref}.{obj.num}")
    return result


def _simplify(pts, tol):
    """Дуглас–Пекер для замкнутого контура."""
    if len(pts) < 8:
        return pts
    pts = np.asarray(pts)

    def rdp(a):
        if len(a) < 3:
            return a
        p0, p1 = a[0], a[-1]
        d = p1 - p0
        L = math.hypot(*d)
        if L < 1e-12:
            dist = np.hypot(*(a - p0).T)
        else:
            dist = np.abs(d[0] * (a[:, 1] - p0[1]) - d[1] * (a[:, 0] - p0[0])) / L
        i = int(np.argmax(dist))
        if dist[i] > tol:
            return np.vstack([rdp(a[:i + 1])[:-1], rdp(a[i:])])
        return np.vstack([p0, p1])
    half = len(pts) // 2
    out = np.vstack([rdp(pts[:half + 1])[:-1], rdp(np.vstack([pts[half:], pts[:1]]))[:-1]])
    return [tuple(p) for p in out]


def pour_polygons(mask):
    """Растровая маска заливки -> векторные многоугольники [(внешний контур, [дырки])], мм, от больших к меньшим."""
    from contourpy import contour_generator, FillType
    z = np.pad(mask.astype(float), 1)
    gen = contour_generator(z=z, fill_type=FillType.OuterOffset)
    polys = []
    pts_list, offs_list = gen.filled(0.5, 1.5)
    for pts, offs in zip(pts_list, offs_list):
        rings = []
        for i in range(len(offs) - 1):
            ring = pts[offs[i]:offs[i + 1]]
            ring = [((x - 1) / RES + 0.5 / RES, (y - 1) / RES + 0.5 / RES) for x, y in ring]
            ring = _simplify(ring[:-1] if ring[0] == ring[-1] else ring, 0.3 / RES)
            if len(ring) >= 3:
                rings.append(ring)
        if not rings:
            continue
        outer, holes = rings[0], rings[1:]
        area = abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(outer, outer[1:] + outer[:1]))) / 2
        if area < MIN_POUR * MIN_POUR * 4:
            continue
        polys.append((area, outer, holes))
    polys.sort(key=lambda p: -p[0])
    return [(o, h) for _, o, h in polys]


