def copper_layer(side, parts, tracks, vias, pours):
    g = Gerber(f"Copper,L{1 if side == 'F' else 2},{'Top' if side == 'F' else 'Bot'}")
    P = pours["pours"][side]
    # 1) заливка земли: готовые многоугольники (зазоры, полоски и острова уже учтены)
    for outer, holes in pour_polygons(pours["pours"][side + "_keep"]):
        g.lp(True)
        g.region(outer)
        if holes:
            g.lp(False)
            for h in holes:
                g.region(h)
    g.lp(True)
    # 2) проводники, площадки, термобарьеры
    for pad in P.thermals:
        g.ap("C", THERMAL_W)
        for seg in P.spokes[id(pad)]:
            g.line(*seg)
    for t in tracks:
        if t["layer"] == side:
            g.ap("C", t["w"])
            g.line(*t["pts"])
    for p in parts:
        for pad in p.pads:
            if not pad.npth and side in pad.layers:
                draw_pad(g, pad)
    for v in vias + pours["stitch"]:
        g.ap("C", v["d"])
        g.flash(v["x"], v["y"])
    return g.text()


def mask_layer(side, parts):
    g = Gerber(f"Soldermask,{'Top' if side == 'F' else 'Bot'}", "Negative")
    for p in parts:
        for pad in p.pads:
            if pad.npth:
                g.ap("C", pad.w + 2 * MASK_EXP)
                g.flash(pad.x, pad.y)
            elif side in pad.layers:
                draw_pad(g, pad, MASK_EXP)
    return g.text()


def paste_layer(side, parts):
    g = Gerber(f"Paste,{'Top' if side == 'F' else 'Bot'}")
    for p in parts:
        for pad in p.pads:
            if not pad.drill and not pad.npth and pad.layers == {side}:
                draw_pad(g, pad)
    return g.text()


def silk_layer(side, parts, extra_strokes):
    g = Gerber(f"Legend,{'Top' if side == 'F' else 'Bot'}")
    for p in parts:
        if (p.side if p.smd else "F") != side:
            continue
        for it in p.silk:
            if it[0] == "line":
                g.ap("C", max(it[5], 0.15))
                g.line(it[1], it[2], it[3], it[4])
            else:
                _, cx, cy, r, w = it
                g.ap("C", max(w, 0.15))
                pts = [(cx + r * math.cos(2 * math.pi * i / 48), cy + r * math.sin(2 * math.pi * i / 48)) for i in range(49)]
                g.polyline(pts)
    for x1, y1, x2, y2, w in extra_strokes:
        g.ap("C", w)
        g.line(x1, y1, x2, y2)
    return g.text()


def edge_layer():
    g = Gerber("Profile,NP")
    g.ap("C", 0.1)
    pts = board_outline_pts(0, n=12)
    g.polyline(pts + [pts[0]])
    return g.text()


def drill_files(parts, vias, stitch):
    def excellon(holes, slots, plated):
        tools = sorted({round(d, 3) for d, x, y in holes} | {round(min(w, h), 3) for w, h, *_ in slots})
        out = ["M48", f"; Irene client board, {'plated' if plated else 'non-plated'} holes",
               f"; #@! TF.FileFunction,{'Plated' if plated else 'NonPlated'},1,2,{'PTH' if plated else 'NPTH'}",
               "FMAT,2", "METRIC"]
        for i, t in enumerate(tools, 1):
            out.append(f"T{i}C{t:.3f}")
        out += ["%", "G90", "G05"]
        for i, t in enumerate(tools, 1):
            out.append(f"T{i}")
            for d, x, y in holes:
                if round(d, 3) == t:
                    out.append(f"X{x:.3f}Y{H - y:.3f}")
            for w, h, x, y in slots:
                if round(min(w, h), 3) == t:
                    L = (max(w, h) - min(w, h)) / 2
                    if w > h:
                        a, b = (x - L, y), (x + L, y)
                    else:
                        a, b = (x, y - L), (x, y + L)
                    out.append(f"X{a[0]:.3f}Y{H - a[1]:.3f}G85X{b[0]:.3f}Y{H - b[1]:.3f}")
        out += ["M30", ""]
        return "\n".join(out)
    pth, slots, npth = [], [], []
    for p in parts:
        for pad in p.pads:
            if pad.npth:
                npth.append((pad.w, pad.x, pad.y))
            elif pad.slot:
                slots.append((pad.slot[0], pad.slot[1], pad.x, pad.y))
            elif pad.drill:
                pth.append((pad.drill, pad.x, pad.y))
    for v in list(vias) + list(stitch):
        pth.append((v["drill"], v["x"], v["y"]))
    return excellon(pth, slots, True), excellon(npth, [], False)
