def _anchor(ref):
    x, y = _BASE[ref][:2]
    if ref == "U1":
        return W - (W0 - x), y            # модуль — в правом верхнем углу, антенна у края
    if ref == "J3":
        return x, y                      # микрофонные штыри — у левого края
    return x * W / W0, y * H / H0


